// Generates the fictional sample documents used by "Load sample shipment" and the docs.
// All companies, numbers and people in these files are invented.
import fs from 'node:fs';
import path from 'node:path';
import PDFDocument from 'pdfkit';
import { containerCheckDigit } from '../backend/lib/checks.js';
import { ROOT } from '../backend/lib/config.js';

const out = path.join(ROOT, 'public', 'samples');
fs.mkdirSync(out, { recursive: true });

const c1 = `KLWU482190${containerCheckDigit('KLWU482190')}`;
const c2 = `KLWU482207${containerCheckDigit('KLWU482207')}`;

const docs = {
  'sample-bill-of-lading.pdf': {
    title: 'BILL OF LADING',
    lines: [
      ['B/L No', 'HLX-NGB-26117'],
      ['Shipper', 'Ningbo Harbourline Ceramics Co. Ltd'],
      ['Consignee', 'Adebayo Home Fittings Ltd'],
      ['Notify Party', 'Same as consignee'],
      ['Vessel / Voyage', 'MV Coral Meridian / 118W'],
      ['Port of Loading', 'Ningbo, China'],
      ['Port of Discharge', 'Lagos, Nigeria'],
      ['Container Nos', `${c1}, ${c2}`],
      ['No. of Packages', '1,200 cartons'],
      ['Gross Weight', '24,180.00 KGS'],
      ['Description of Goods', 'Glazed ceramic floor tiles, 600 x 600 mm'],
    ],
  },
  'sample-commercial-invoice.pdf': {
    title: 'COMMERCIAL INVOICE',
    lines: [
      ['Invoice No', 'NHC-INV-2026-0412'],
      ['Invoice Date', '02 October 2026'],
      ['Seller', 'Ningbo Harbourline Ceramics Co. Ltd'],
      ['Buyer', 'Adebayo Home Fittings Limited'],
      ['Currency', 'USD'],
      ['Incoterms', 'FOB Ningbo'],
      ['Description of Goods', 'Glazed ceramic floor tiles, 600 x 600 mm, 1.44 m2 per carton'],
      ['HS Code', '6907.21'],
      ['Total Quantity', '1,728.00 m2'],
      ['Total Invoice Value', '15,552.00'],
    ],
  },
  'sample-packing-list.pdf': {
    title: 'PACKING LIST',
    lines: [
      ['Invoice Ref', 'NHC-INV-2026-0412'],
      ['Consignee', 'Adebayo Home Fittings Ltd.'],
      ['Container Nos', `${c1}, ${c2}`],
      ['Total Packages', '1,180 cartons'],
      ['Total Quantity', '1,699.20 m2'],
      ['Total Gross Weight', '24,180.00 KGS'],
      ['Total Net Weight', '23,410.00 KGS'],
    ],
  },
};

for (const [file, spec] of Object.entries(docs)) {
  const doc = new PDFDocument({ size: 'A4', margin: 56, info: { Title: `${spec.title} (sample)`, Author: 'Klearway sample data' } });
  doc.pipe(fs.createWriteStream(path.join(out, file)));
  doc.fontSize(9).fillColor('#B8402A').text('SAMPLE DATA: FICTIONAL DOCUMENT FOR DEMONSTRATION ONLY');
  doc.moveDown(0.8);
  doc.fontSize(20).fillColor('#0F1D1C').text(spec.title);
  doc.moveDown(0.8);
  doc.fontSize(11).fillColor('#0F1D1C');
  for (const [k, v] of spec.lines) {
    doc.text(`${k}: ${v}`);
    doc.moveDown(0.35);
  }
  doc.moveDown(2);
  doc.fontSize(8).fillColor('#6B817E').text('Generated by Klearway for product demonstrations. Companies, references and figures are invented.');
  doc.end();
}
console.log(`Sample documents written to ${out} (containers ${c1}, ${c2})`);
